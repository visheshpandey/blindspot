// Re-check "what changed", WhatsApp share and voice button. Usage: node scripts/recheck-check.mjs (backend on :8000)
import { chromium } from 'playwright'
const BASE = process.env.BASE_URL || 'http://localhost:5173'
const b = await chromium.launch({ channel: 'chromium', args: ['--use-angle=d3d11', '--enable-gpu'] })
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } })
await ctx.addInitScript(() => localStorage.setItem('blindspot.tour.seen', '1'))
const p = await ctx.newPage()
const errors = []
p.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
await p.request.post('http://localhost:8000/traplab/update?updated=false')
await p.goto(`${BASE}/#/`); await p.waitForSelector('.traplab-card')
await p.locator('.traplab-card .primary-button').click()
await p.waitForSelector('.trap-scorecard', { timeout: 120000 })
console.log('first run score:', await p.locator('.trap-score-num').innerText(), '| what-changed shown:', await p.locator('.what-changed').count())
const wa = await p.locator('.whatsapp-button').getAttribute('href')
console.log('WhatsApp link:', decodeURIComponent(wa).slice(0, 260).replace(/\n/g, ' / '))
await p.locator('.trap-simulate button').click()
await p.waitForTimeout(500)
await p.locator('.report-title-actions button', { hasText: 'Re-check' }).click()
await p.waitForSelector('.what-changed', { timeout: 120000 })
console.log('CHANGED:', (await p.locator('.what-changed').innerText()).replace(/\n+/g, ' | '))
console.log('RAW:', JSON.stringify(await p.evaluate(() => JSON.parse(localStorage.getItem('blindspot.history.v1'))[0].changes.items)).slice(0, 700))
await p.screenshot({ path: 'screenshots/recheck.png' })
await p.request.post('http://localhost:8000/traplab/update?updated=false')
await p.goto(`${BASE}/#/new`); await p.waitForSelector('.ni-form')
console.log('voice button present:', await p.locator('.voice-button').count())
console.log('console errors:', errors.length, errors.slice(0, 2))
await b.close()
