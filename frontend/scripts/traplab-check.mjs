// Trap Lab end to end. Usage: node scripts/traplab-check.mjs   (OFFLINE=1 blocks the backend: recorded run)
import { chromium } from 'playwright'
const BASE = process.env.BASE_URL || 'http://localhost:5173'
const OFFLINE = process.env.OFFLINE === '1'
const b = await chromium.launch({ channel: 'chromium', args: ['--use-angle=d3d11', '--enable-gpu'] })
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } })
await ctx.addInitScript(() => localStorage.setItem('blindspot.tour.seen', '1'))
const p = await ctx.newPage()
const errors = []
p.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
if (OFFLINE) await p.route('http://localhost:8000/**', (r) => r.abort())
await p.goto(`${BASE}/#/`); await p.waitForSelector('.traplab-card')
await p.waitForTimeout(1500)
await p.locator('.traplab-card').scrollIntoViewIfNeeded()
await p.screenshot({ path: 'screenshots/traplab-overview.png' })
await p.locator('.versus-panel').scrollIntoViewIfNeeded()
await p.screenshot({ path: 'screenshots/traplab-versus.png' })
const t0 = Date.now()
await p.locator('.traplab-card .primary-button').click()
await p.waitForSelector('.source-progress li', { timeout: 15000 }).catch(() => {})
console.log('progress rows:', await p.locator('.source-progress li').count())
await p.waitForSelector('.trap-scorecard', { timeout: 120000 })
console.log(`scorecard after ${((Date.now() - t0) / 1000).toFixed(0)} s:`, await p.locator('.trap-score-num').innerText(), '|', await p.locator('.demo-run-badge').count() ? 'saved demo run' : 'live run')
console.log('missed:', await p.locator('.trap-scorecard li.missed').count())
await p.screenshot({ path: 'screenshots/traplab-report.png' })
await p.locator('.board-card.tone-yellow .text-link').first().click(); await p.waitForSelector('.detail-drawer')
const href = await p.locator('.detail-drawer .evidence-foot a').first().getAttribute('href')
console.log('open-source link:', href)
console.log('console errors (excluding blocked network):', errors.filter((e) => !/Failed to load|net::/.test(e)).length)
await b.close()
