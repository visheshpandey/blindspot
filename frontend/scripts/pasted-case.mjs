// Final check 1: a live pasted-text case. Runs it through the real form, then checks the report.
import { chromium } from 'playwright'
const BASE = process.env.BASE_URL || 'http://localhost:5173'
const TEXT = `Post Matric Scholarship for SC Students 2026-27. Eligibility: students whose parents' annual income from all sources does not exceed Rs 2,50,000 are eligible. Documents required: income certificate issued by the competent authority, caste certificate, previous year mark sheet and Aadhaar-seeded bank account details. The last date to apply on the portal for the 2026-27 cycle is 31 October 2026. Scholarship is renewed each year on promotion to the next class.`
const b = await chromium.launch({ channel: 'chromium', args: ['--use-angle=d3d11', '--enable-gpu'] })
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } })
await ctx.addInitScript(() => localStorage.setItem('blindspot.tour.seen', '1'))
const p = await ctx.newPage()
const errors = []
p.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
await p.goto(`${BASE}/#/new`); await p.waitForSelector('.ni-form')
const rows = p.locator('.source-block')
await rows.nth(0).locator('input').fill('https://scholarships.gov.in/')
await rows.nth(0).locator('.paste-toggle').click()
await rows.nth(0).locator('.paste-area').fill(TEXT)
await rows.nth(1).locator('.remove-source').click()
const t0 = Date.now()
await p.locator('button[type=submit]').click()
await p.waitForSelector('.source-progress li', { timeout: 20000 })
await p.screenshot({ path: 'screenshots/polish-analyzing.png' })
await p.waitForSelector('.verdict-card', { timeout: 180000 })
console.log('run took', ((Date.now() - t0) / 1000).toFixed(0), 's')
await p.waitForTimeout(800)
console.log('VERDICT:', await p.locator('.verdict-word').innerText(), '|', await p.locator('.verdict-count').innerText())
await p.locator('.verdict-more summary').click()
console.log('WHY:', (await p.locator('.why-list').innerText()).replace(/\n+/g, ' / '))
console.log('FIX:', (await p.locator('.why-fix').innerText()).replace(/\n+/g, ' / '))
console.log('STRENGTH:', (await p.locator('.board-card .strength').allInnerTexts()).join(' ; '))
console.log('PILLS:', (await p.locator('.board-card header .status-pill').allInnerTexts()).join(' ; '))
console.log('SOURCE:', (await p.locator('.source-card-row').first().innerText()).replace(/\n+/g, ' / '))
console.log('LIVE STAMPS in report data:', await p.evaluate(() => document.body.innerText.includes('Confirmed on live page')))
await p.screenshot({ path: 'screenshots/polish-report.png', fullPage: false })
console.log('console errors:', errors.length, errors.slice(0, 3))
await b.close()
